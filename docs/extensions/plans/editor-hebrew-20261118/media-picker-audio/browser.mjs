import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const out=dirname(fileURLToPath(import.meta.url)), root=resolve(out,"../../../../..");
const require=createRequire(resolve(root,"extensions/package.json"));
const {chromium,expect}=require("@playwright/test");
const run=process.argv[2]||"after";
const source=resolve(root,"packages/web/src/features/quizz/components/QuestionEditor/MediaLibrary/use-media-library-extensions.ts");
const sourceSha256=createHash("sha256").update(await readFile(source)).digest("hex");
const browser=await chromium.launch({channel:"msedge",headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900}});
page.setDefaultTimeout(10000);
const result={run,sourceSha256,boundary:"Actual application MediaLibrary/React/query/editor context/i18n and native controls; controlled Audio instances and isolated empty media HTTP, no audible/decoded playback claim.",checks:[],pageErrors:[]};
page.on("pageerror",e=>result.pageErrors.push(String(e)));
await page.route("**/api/**",route=>route.fulfill({json:{media:[]}}));
const check=name=>result.checks.push({name,status:"PASS"});
const active=loc=>expect(loc.locator("svg.lucide-volume-2")).toHaveCount(1);
const inactive=loc=>expect(loc.locator("svg.lucide-music")).toHaveCount(1);
const audioState=async(index)=>page.evaluate(index=>{const a=window.__audioHarness.audios[index<0?window.__audioHarness.audios.length+index:index];return {paused:a.paused,time:a.currentTime,endedDetached:a.onended===null,errorDetached:a.onerror===null,pauseCalls:a.pauseCalls};},index);
try{
 await page.goto("http://127.0.0.1:3186/media-picker-audio-proof.html",{waitUntil:"domcontentloaded",timeout:60000});
 await page.getByTestId("media-scope-builtin").click();
 const buttons=page.locator('[data-testid^="builtin-sound-preview-"]'), a=buttons.nth(0), b=buttons.nth(1);
 await expect(a).toBeVisible();await expect(b).toBeVisible();
 expect(await page.evaluate(()=>window.__audioHarness.audios.length)).toBe(0); check("Mount and library opening do not create or autoplay audio");
 await a.click();await active(a);
 await page.evaluate(()=>{const h=window.__audioHarness;h.oldEnded=h.audios[0].onended;h.oldError=h.audios[0].onerror;});
 await b.click();await active(b);await inactive(a);
 const stopped=await audioState(0);
 expect(stopped.paused).toBe(true);expect(stopped.time).toBe(0);check("Switch stops and rewinds previous cue");
 await page.evaluate(async()=>{const h=window.__audioHarness;h.oldEnded?.();h.oldError?.();h.audios[0].rejectPlay(new Error("late canceled playback"));await Promise.resolve();});
 await active(b);check("Queued stale ended/error/rejected play preserve newer preview and audio owner");
 expect(stopped.endedDetached).toBe(true);expect(stopped.errorDetached).toBe(true);check("Previous cue handlers detach before stop");
 await page.screenshot({path:resolve(out,run+"-new-owner.png"),fullPage:true});
 await b.click();await inactive(b);expect(await audioState(1)).toMatchObject({paused:true,time:0,endedDetached:true,errorDetached:true});check("Clicking same cue stops and detaches it");
 await a.click();await active(a);await page.evaluate(()=>window.__audioHarness.audios.at(-1).onended());await inactive(a);
 expect(await audioState(-1)).toMatchObject({paused:true,time:0,endedDetached:true,errorDetached:true});check("Current ended event releases and resets owned audio");
 await b.click();await active(b);await page.evaluate(()=>window.__audioHarness.audios.at(-1).onerror());await inactive(b);check("Current media error releases only current owner");
 await a.click();await active(a);await page.evaluate(async()=>{window.__audioHarness.audios.at(-1).rejectPlay(new Error("autoplay rejected"));await Promise.resolve();});await inactive(a);check("Current rejected play resets preview and allows recovery");
 await b.click();await active(b);await page.getByRole("button",{name:"סגירה",exact:true}).click();
 expect(await audioState(-1)).toMatchObject({paused:true,time:0,endedDetached:true,errorDetached:true});check("Actual dialog close stops and detaches audio");
 await page.evaluate(()=>window.__audioHarness.open());await page.getByTestId("media-scope-builtin").click();
 await a.click();await active(a);await page.evaluate(()=>{const h=window.__audioHarness;h.unmountEnded=h.audios.at(-1).onended;h.unmountError=h.audios.at(-1).onerror;h.unmount();});
 await expect(buttons).toHaveCount(0);
 expect(await audioState(-1)).toMatchObject({paused:true,time:0,endedDetached:true,errorDetached:true});
 await page.evaluate(async()=>{const h=window.__audioHarness;h.unmountEnded?.();h.unmountError?.();h.audios.at(-1).rejectPlay(new Error("late unmounted rejection"));await Promise.resolve();});
 check("Unmount stops audio and late ended/error/rejection has no owner");
 expect(result.pageErrors).toEqual([]);check("No page errors through cleanup and callback races");
 result.status="PASS";
}catch(e){result.status="FAIL";result.error=String(e);process.exitCode=1;await page.screenshot({path:resolve(out,run+"-failure.png"),fullPage:true}).catch(()=>{});}
finally{await writeFile(resolve(out,run+".json"),JSON.stringify(result,null,2)+"\n");console.log(JSON.stringify(result));await browser.close();}
