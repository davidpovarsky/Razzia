export type BuilderTextKey = keyof typeof builderStrings

const instance = createInstance()
void instance.init({
  initAsync: false,
  fallbackLng: false,
  ns: ["tadazzThemeBuilder"],
  defaultNS: "tadazzThemeBuilder",
  resources: Object.fromEntries(
    languages.map((language, index) => [
      language,
      {
        tadazzThemeBuilder: Object.fromEntries(
          Object.entries(builderStrings).map(([key, values]) => [
            key,
            values[index],
          ]),
        ),
      },
    ]),
  ),
})

export function builderText(locale: PreviewLocale) {
  if (!languages.includes(locale)) {
    throw new Error("theme-builder:unsupported-locale")
  }

  return (key: BuilderTextKey) => instance.t(key, { lng: locale })
}
