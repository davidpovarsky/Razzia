export function consentText(locale: PreviewLocale) {
  const instance = createInstance()
  void instance.init({
    lng: locale,
    fallbackLng: false,
    initAsync: false,
    interpolation: { escapeValue: false },
    ns: ["tadazzOAuthConsent"],
    defaultNS: "tadazzOAuthConsent",
    resources: {
      [locale]: {
        tadazzOAuthConsent: Object.fromEntries(
          keys.map((key, index) => [key, translations[locale][index]]),
        ),
      },
    },
  })
  return (key: Key) => String(instance.t(key))
}
