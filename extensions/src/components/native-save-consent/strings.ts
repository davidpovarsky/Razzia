export function nativeSaveConsentText(locale: PreviewLocale) {
  const instance = createInstance()
  void instance.init({
    lng: locale,
    fallbackLng: false,
    initAsync: false,
    interpolation: { escapeValue: false },
    ns: ["tadazzNativeSaveConsent"],
    defaultNS: "tadazzNativeSaveConsent",
    resources: {
      [locale]: {
        tadazzNativeSaveConsent: Object.fromEntries(
          keys.map((key, index) => [key, translations[locale][index]]),
        ),
      },
    },
  })
  return (key: Key) => String(instance.t(key))
}
