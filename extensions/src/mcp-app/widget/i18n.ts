export function createWidgetI18n() {
  const instance = i18next.createInstance()
  void instance.init({
    resources,
    lng: "en",
    fallbackLng: "en",
    defaultNS: "widget",
    initAsync: false,
    interpolation: { escapeValue: false },
  })

  return instance
}

export function hostLocale(value?: string): Locale {
  const base = value?.split(/[-_]/u)[0]

  return locales.includes(base as Locale) ? (base as Locale) : "en"
}

