export const resources: Record<string, { widget: Record<string, string> }> =
  Object.fromEntries(
    locales.map((locale) => {
      const values =
        locale === "en"
          ? en
          : Object.fromEntries(
              Object.keys(en).map((key, index) => [key, rows[locale][index]]),
            )

      return [locale, { widget: values }]
    }),
  )

