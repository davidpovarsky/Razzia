interface OriginalInventoryAsset {
  readonly family: string
  readonly name: string
  readonly kind: string
  readonly url: string
  readonly sha256: string
  readonly bytes: number
}

// These checked-in inventories pin the reviewed, generated bytes. They are not
// caller manifests or URL-prefix grants: every expected family/name must appear
// exactly once, and deployment admission still verifies the exact bytes below.
function originalReviewedAssets<P extends "background" | "audio">(
  inventory: readonly OriginalInventoryAsset[],
  names: readonly string[],
  purpose: P,
) {
  if (inventory.length !== ORIGINAL_THEME_IDS.length * names.length) {
    throw new Error("Reviewed original asset inventory incomplete")
  }

  const seen = new Set<string>()
  const extension = purpose === "audio" ? "wav" : "png"

  return Object.freeze(
    inventory.map((asset) => {
      const key = `${asset.family}/${asset.name}`

      if (
        !isOriginalThemeId(asset.family) ||
        !names.includes(asset.name) ||
        asset.kind !== (purpose === "audio" ? "audio" : "image") ||
        asset.url !== `/tadazz-show/originals/${key}.${extension}` ||
        !/^[a-f0-9]{64}$/u.test(asset.sha256) ||
        !Number.isSafeInteger(asset.bytes) ||
        asset.bytes <= 0 ||
        asset.bytes > 100_000_000 ||
        seen.has(key)
      ) {
        throw new Error("Reviewed original asset inventory rejected")
      }

      seen.add(key)

      return Object.freeze({
        assetId:
          purpose === "audio"
            ? `${asset.family}.sound.${asset.name}`
            : `${asset.family}.${asset.name}`,
        sha256: asset.sha256,
        bytes: asset.bytes,
        url: asset.url,
        mime:
          purpose === "audio" ? ("audio/wav" as const) : ("image/png" as const),
        purpose,
        label: purpose,
        families: Object.freeze([asset.family]),
      })
    }),
  )
}

